import test from 'node:test';
import assert from 'node:assert/strict';

import {
    deriveIdentity, deriveNextIdentity, describeIdentity, isMusical, parseDurationText,
    parseTopicDescription, parseYtMusicByline,
} from '../shared/song-identity.js';

const TOPIC = `Provided to YouTube by Sony Music Entertainment

Never Gonna Give You Up · Rick Astley

Whenever You Need Somebody

℗ 1987 Sony Music Entertainment UK Limited

Released on: 1987-11-12

Auto-generated by YouTube.`;

const raw = overrides => ({
    host: 'www.youtube.com', videoId: 'abc', title: '', author: '', lengthSeconds: 213,
    category: '', musicVideoType: '', description: '', musicCards: [], mediaSession: null, ytmByline: '',
    ...overrides,
});

test('Topic descriptions give song, artists, album and year', () => {
    assert.deepEqual(parseTopicDescription(TOPIC), {
        title: 'Never Gonna Give You Up', artist: 'Rick Astley', album: 'Whenever You Need Somebody', year: '1987',
    });
    assert.deepEqual(parseTopicDescription('Provided to YouTube by X\n\nSong · A · B\n\n℗ 2001 X'), {
        title: 'Song', artist: 'A, B', album: '', year: '2001',
    });
    assert.equal(parseTopicDescription('Just a video'), null);
});

test('YouTube Music bylines carry album and year only for songs', () => {
    assert.deepEqual(parseYtMusicByline('Rick Astley • Whenever You Need Somebody • 1987'), {artist: 'Rick Astley', album: 'Whenever You Need Somebody', year: '1987'});
    assert.deepEqual(parseYtMusicByline('Rick Astley • 1.8B views • 19M likes'), {artist: 'Rick Astley', album: '', year: ''});
});

test('duration text parses clocks and spoken labels', () => {
    assert.equal(parseDurationText('3:24'), 204);
    assert.equal(parseDurationText('1:02:03'), 3723);
    assert.equal(parseDurationText('3 minutes, 24 seconds'), 204);
    assert.equal(parseDurationText('live'), 0);
});

test('music detection uses category, type, Topic, cards and host', () => {
    assert.equal(isMusical(raw({})), false);
    assert.equal(isMusical(raw({category: 'Music'})), true);
    assert.equal(isMusical(raw({author: 'Someone - Topic'})), true);
    assert.equal(isMusical(raw({host: 'music.youtube.com'})), true);
    assert.equal(isMusical(raw({musicCards: [{title: 'a', artist: 'b', album: ''}]})), true);
});

test('a title that calls itself music counts as music', () => {
    for (const title of [
        '"The Lantern on the Hill" - British Folk song', 'Old Hundredth (hymn)', 'Wellerman - Sea Shanty',
        'Band - Song (Official Video)', 'Band - Song [Acoustic Cover]', 'Band - Song (Lyrics)', 'Brahms Lullaby',
    ])
        assert.equal(isMusical(raw({title})), true, title);
    for (const title of [
        'A Day In The Life Of A Beekeeper', 'How to cover a couch', 'Official Video Game Trailer', 'Songbird nest cam',
    ])
        assert.equal(isMusical(raw({title})), false, title);
});

test('a quoted phrase ending a title is the song, with any artist before it', () => {
    // A folk song filed under People & Blogs, with no music card or Topic channel.
    const folk = deriveIdentity(raw({
        videoId: 'folkclip001', title: '"The Lantern on the Hill" - British Folk song',
        author: 'Example Folk Archive', lengthSeconds: 54, category: 'People & Blogs',
    }));
    assert.deepEqual([folk.musical, folk.title, folk.artist], [true, 'The Lantern on the Hill', 'Example Folk Archive']);

    const credited = deriveIdentity(raw({title: 'Pete Seeger "Where Have All the Flowers Gone" (Live)', author: 'Archive'}));
    assert.deepEqual([credited.artist, credited.title], ['Pete Seeger', 'Where Have All the Flowers Gone']);
    const curly = deriveIdentity(raw({title: 'Band – “Song”', author: 'Uploader'}));
    assert.deepEqual([curly.artist, curly.title], ['Band', 'Song']);
    const nickname = deriveIdentity(raw({title: '"Weird Al" Yankovic - Amish Paradise', author: 'alyankovicVEVO'}));
    assert.deepEqual([nickname.artist, nickname.title], ['"Weird Al" Yankovic', 'Amish Paradise']);
});

test('identity sources rank Topic, YouTube Music, music card, then video title', () => {
    const topic = deriveIdentity(raw({description: TOPIC, title: 'Never Gonna Give You Up', author: 'Rick Astley - Topic'}));
    assert.equal(topic.source, 'topic');
    assert.equal(topic.reliable, true);
    assert.equal(topic.year, '1987');

    const ytm = deriveIdentity(raw({
        host: 'music.youtube.com', musicVideoType: 'MUSIC_VIDEO_TYPE_ATV',
        mediaSession: {title: 'Song', artist: 'Band', album: ''}, ytmByline: 'Band • Album • 1999',
    }));
    assert.deepEqual([ytm.source, ytm.title, ytm.artist, ytm.album, ytm.year, ytm.reliable], ['youtube-music', 'Song', 'Band', 'Album', '1999', true]);

    const card = deriveIdentity(raw({
        title: 'Rick Astley - Never Gonna Give You Up (Official Video) (4K Remaster)', author: 'Rick Astley', category: 'Music',
        musicCards: [{title: 'Never Gonna Give You Up (7" Mix)', artist: 'Rick Astley', album: 'Whenever You Need Somebody'}],
    }));
    assert.deepEqual([card.source, card.title, card.album, card.musical], ['music-card', 'Never Gonna Give You Up (7" Mix)', 'Whenever You Need Somebody', true]);

    const parsed = deriveIdentity(raw({title: 'Queen - Bohemian Rhapsody (Official Video Remastered)', author: 'Queen Official'}));
    assert.deepEqual([parsed.source, parsed.artist, parsed.title, parsed.reliable], ['video-title', 'Queen', 'Bohemian Rhapsody', false]);
});

test('next-video identities trust YouTube Music and Topic listings', () => {
    const topic = deriveNextIdentity({videoId: 'n', title: 'Song', byline: 'Band - Topic', durationSeconds: 200, host: 'www.youtube.com'});
    assert.deepEqual([topic.artist, topic.title, topic.reliable], ['Band', 'Song', true]);
    const video = deriveNextIdentity({videoId: 'n', title: 'Band - Song (Official Video)', byline: 'BandVEVO', durationSeconds: 200, host: 'www.youtube.com'});
    assert.deepEqual([video.artist, video.title, video.reliable, video.musical], ['Band', 'Song', false, true]);
});

test('a next-video listing naming no artist is not treated as a song', () => {
    // youtube.com's autoplay pick comes from the player's next button: a title, no channel.
    const parsed = deriveNextIdentity({videoId: 'n', title: 'Band - Song (Official Video)', byline: '', durationSeconds: 200, host: 'www.youtube.com'});
    assert.deepEqual([parsed.artist, parsed.title, parsed.musical], ['Band', 'Song', true]);
    const bare = deriveNextIdentity({videoId: 'n', title: 'A Day In The Life Of A Beekeeper', byline: '', durationSeconds: 870, host: 'www.youtube.com'});
    assert.equal(bare.musical, false);
    const folk = deriveNextIdentity({videoId: 'n', title: '"Scarborough Fair" - English folk song', byline: '', durationSeconds: 150, host: 'www.youtube.com'});
    assert.deepEqual([folk.title, folk.musical], ['Scarborough Fair', true]);
});

test('identity text is Artist - Song - Year - Album, skipping unknowns', () => {
    assert.equal(describeIdentity({artist: 'A', title: 'S', year: '', album: 'Al'}), 'A - S - Al');
});
